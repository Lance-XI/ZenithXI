-- Source: https://ffxiclopedia.fandom.com/wiki/Experience_Points?oldid=334881#Base_Experience
--
-- The difficulty thresholds below only mean anything when the base EXP they are
-- graded against is era too. That data used to live in modules/wotg/sql/2007_exp_tables.sql,
-- which rewrote the r1-r20 columns of the `exp_table` table. Upstream dropped both the
-- table and the file and moved base EXP into xi.data.experiencePoints.baseTable
-- (scripts/data/experience_table.lua), so the matrix is restored here instead.
-- Without it an even match is worth 200 base EXP rather than the era 100, which
-- roughly doubles rates from level 51 up and shifts every /check up about two tiers.
-----------------------------------
require('modules/module_utils')
-----------------------------------

local moduleName = 'original_exp_curve'

